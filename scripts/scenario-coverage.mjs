#!/usr/bin/env node
// Coverage by scenario id (AD-20, R18): reads every suite's JSON report (the
// Vitest unit, component, integration, contract, profile and
// contract-unavailable reports and the Playwright e2e report), takes each test
// title's leading scenario id, and writes coverage/scenarios.md, listing each
// id by suite.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const coverageDir = `${root}coverage`;
const vitestSuites = ['unit', 'component', 'integration', 'contract', 'profile', 'contract-unavailable'];
const reports = {
  ...Object.fromEntries(vitestSuites.map((suite) => [suite, `${coverageDir}/${suite}-report.json`])),
  e2e: `${coverageDir}/e2e-report.json`,
};
// A title starts with one or more space-separated scenario ids, e.g. "E1 E7 E8 …".
const LEADING_IDS = /^(?:[UIKE]\d+(?:\s+|$))+/;

/** Every scenario id at the start of a title, or [null] when there is none. */
function scenarioIds(title) {
  const ids = title.match(LEADING_IDS)?.[0].trim().split(/\s+/) ?? [];
  return ids.length > 0 ? ids : [null];
}

/** @typedef {{ suite: string, id: string | null, title: string, passed: boolean }} Result */

/** @returns {Result[]} */
function fromVitest(suite, path) {
  const report = JSON.parse(readFileSync(path, 'utf8'));
  return report.testResults.flatMap((file) =>
    file.assertionResults.flatMap((test) =>
      scenarioIds(test.title).map((id) => ({
        suite,
        id,
        title: test.title,
        passed: test.status === 'passed',
      })),
    ),
  );
}

/** @returns {Result[]} */
function fromPlaywright(path) {
  const report = JSON.parse(readFileSync(path, 'utf8'));
  const results = [];
  const walk = (suite) => {
    for (const spec of suite.specs ?? []) {
      for (const test of spec.tests) {
        for (const id of scenarioIds(spec.title)) {
          results.push({
            suite: `e2e · ${test.projectName}`,
            id,
            title: spec.title,
            passed: test.status === 'expected',
          });
        }
      }
    }
    for (const child of suite.suites ?? []) walk(child);
  };
  for (const suite of report.suites) walk(suite);
  return results;
}

const missing = [];
const results = [];
for (const [name, path] of Object.entries(reports)) {
  if (!existsSync(path)) {
    missing.push(name);
    continue;
  }
  results.push(...(name === 'e2e' ? fromPlaywright(path) : fromVitest(name, path)));
}

const byId = new Map();
for (const result of results) {
  const id = result.id ?? '(no id)';
  if (!byId.has(id)) byId.set(id, []);
  byId.get(id).push(result);
}

const order = (id) => {
  const m = id.match(/^([UIKE])(\d+)$/);
  return m ? `${'UIKE'.indexOf(m[1])}${m[2].padStart(4, '0')}` : `9${id}`;
};
const ids = [...byId.keys()].sort((a, b) => order(a).localeCompare(order(b)));

const lines = [
  '# Coverage by scenario id',
  '',
  `Generated by \`scripts/scenario-coverage.mjs\` on ${new Date().toISOString()} from the ${vitestSuites.join(', ')} (Vitest) and e2e (Playwright) JSON reports.`,
  '',
  '| Scenario | Result | Passed | Failed | Suites |',
  '|---|---|---|---|---|',
];
for (const id of ids) {
  const tests = byId.get(id);
  const passed = tests.filter((t) => t.passed).length;
  const failed = tests.length - passed;
  const suites = [...new Set(tests.map((t) => t.suite))].join(', ');
  lines.push(`| ${id} | ${failed === 0 ? 'pass' : 'fail'} | ${passed} | ${failed} | ${suites} |`);
}
if (missing.length > 0) {
  lines.push('', `Missing reports: ${missing.join(', ')}. Those suites did not run or did not finish.`);
}
lines.push('', '## Tests', '');
// A test with several ids is listed once.
const tests = new Map(results.map((r) => [`${r.suite}\u0000${r.title}`, r]));
for (const result of tests.values()) {
  lines.push(`- ${result.passed ? 'pass' : 'FAIL'} · ${result.suite} · ${result.title}`);
}

writeFileSync(`${coverageDir}/scenarios.md`, `${lines.join('\n')}\n`);
console.log(`Wrote coverage/scenarios.md (${ids.length} scenario ids, ${tests.size} tests)`);
if (missing.length > 0) {
  console.error(`Missing reports: ${missing.join(', ')}`);
  process.exit(1);
}
